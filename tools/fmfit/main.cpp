// Fits the 3-cell Fletcher-Munson cascade (low shelf, bell, high shelf) to the
// ISO 226:2003 compensation curve and prints the kFmCells table for
// dsp/bands/FletcherMunson.cpp.
//
// The cell gains scale linearly with the phon delta, so the fit minimizes the
// error over several deltas at once.

#include <array>
#include <cmath>
#include <cstdio>
#include <vector>

#include "bands/BandDesign.h"
#include "bands/Iso226.h"
#include "common/Math.h"

using namespace eeq;

namespace {

constexpr double kFs = 96000.0;
constexpr int kParams = 9;
using Vec = std::array<double, kParams>;

// Parameter vector: log(f), log(q), gain-per-phon for each cell.
BandDesign makeDesign(const Vec& v, double phon) {
    const SvfShape shapes[3] = {SvfShape::LowShelf, SvfShape::Bell, SvfShape::HighShelf};
    BandDesign d;
    d.topology = BandTopology::Serial;
    for (int c = 0; c < 3; ++c)
        d.cells[d.numCells++] = designSvf(shapes[c], std::exp(v[3 * c]), std::exp(v[3 * c + 1]), v[3 * c + 2] * phon, kFs);
    d.postGain = 1.0 / std::abs(bandResponse(d, 1000.0, kFs));
    return d;
}

double cost(const Vec& v) {
    double err = 0.0;
    for (double phon : {5.0, 20.0, 40.0}) {
        const BandDesign d = makeDesign(v, phon);
        for (int i = 0; i < iso226::kNumFreqs; ++i) {
            const double target = phon * iso226::compensationPerPhon(i);
            const double got = 20.0 * std::log10(std::abs(bandResponse(d, iso226::kFreqs[i], kFs)));
            err += (got - target) * (got - target) / (phon * phon);
        }
    }
    // Keep Q values in a sane range.
    for (int c = 0; c < 3; ++c) {
        const double q = std::exp(v[3 * c + 1]);
        if (q < 0.3) err += 100.0 * (0.3 - q);
        if (q > 4.0) err += 100.0 * (q - 4.0);
    }
    return err;
}

Vec nelderMead(Vec start, int iterations) {
    std::vector<Vec> simplex(kParams + 1, start);
    for (int i = 0; i < kParams; ++i) simplex[i + 1][i] += (i % 3 == 2) ? 0.05 : 0.3;
    std::vector<double> f(kParams + 1);
    for (int i = 0; i <= kParams; ++i) f[i] = cost(simplex[i]);

    for (int it = 0; it < iterations; ++it) {
        // Order.
        for (int i = 0; i <= kParams; ++i)
            for (int j = i + 1; j <= kParams; ++j)
                if (f[j] < f[i]) std::swap(f[i], f[j]), std::swap(simplex[i], simplex[j]);
        Vec centroid{};
        for (int i = 0; i < kParams; ++i)
            for (int k = 0; k < kParams; ++k) centroid[k] += simplex[i][k] / kParams;
        auto along = [&](double t) {
            Vec p;
            for (int k = 0; k < kParams; ++k) p[k] = centroid[k] + t * (simplex[kParams][k] - centroid[k]);
            return p;
        };
        const Vec r = along(-1.0);
        const double fr = cost(r);
        if (fr < f[0]) {
            const Vec e = along(-2.0);
            const double fe = cost(e);
            simplex[kParams] = fe < fr ? e : r, f[kParams] = std::min(fe, fr);
        } else if (fr < f[kParams - 1]) {
            simplex[kParams] = r, f[kParams] = fr;
        } else {
            const Vec c = along(0.5);
            const double fc = cost(c);
            if (fc < f[kParams]) {
                simplex[kParams] = c, f[kParams] = fc;
            } else {
                for (int i = 1; i <= kParams; ++i) {
                    for (int k = 0; k < kParams; ++k) simplex[i][k] = simplex[0][k] + 0.5 * (simplex[i][k] - simplex[0][k]);
                    f[i] = cost(simplex[i]);
                }
            }
        }
    }
    return simplex[0];
}

}  // namespace

int main() {
    Vec v = {std::log(100.0), std::log(0.5), 0.5,
             std::log(3500.0), std::log(1.0), -0.03,
             std::log(10000.0), std::log(0.7), 0.15};
    for (int restart = 0; restart < 8; ++restart) v = nelderMead(v, 4000);

    std::printf("// Generated by tools/fmfit (residual cost %.5f).\n", cost(v));
    std::printf("const std::array<FmCell, 3> kFmCells = {{\n");
    const char* names[3] = {"LowShelf", "Bell", "HighShelf"};
    for (int c = 0; c < 3; ++c)
        std::printf("    {SvfShape::%s, %.2f, %.4f, %.5f},\n", names[c], std::exp(v[3 * c]), std::exp(v[3 * c + 1]), v[3 * c + 2]);
    std::printf("}};\n\n");

    std::printf("// Fit error at a 20-phon delta:\n//   Hz      target    fit\n");
    const BandDesign d = makeDesign(v, 20.0);
    for (int i = 0; i < iso226::kNumFreqs; ++i) {
        const double f = iso226::kFreqs[i];
        std::printf("//   %-7.1f %6.2f  %6.2f\n", f, 20.0 * iso226::compensationPerPhon(i),
                    20.0 * std::log10(std::abs(bandResponse(d, f, kFs))));
    }
    return 0;
}
